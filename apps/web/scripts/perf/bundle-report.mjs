#!/usr/bin/env node
/**
 * Bundle report for a Vite build of the web app.
 *
 *   node scripts/perf/bundle-report.mjs [distDir] [--json out.json] [--why] [--files] [--top N]
 *
 * "Initial" is exactly what index.html makes the browser fetch before the app can run: the entry
 * module, every `<link rel="modulepreload">` Vite emitted for its static import graph, and the
 * stylesheets. Everything else is lazy (dynamic imports, workers, WebAssembly, fonts that load by
 * unicode-range). Sizes are raw bytes, gzip (level 9, what most CDNs and `vite preview` serve) and
 * brotli; the APK stores assets deflated, so gzip is also a fair proxy for install size.
 *
 * `--why` attributes the initial JavaScript to its origins using the source maps (decoding the VLQ
 * mappings and counting generated bytes per original source), so a regression report says *what*
 * got pulled in, not just that the number went up. `--files` lists the largest single sources.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
import { pathToFileURL } from 'node:url';

/** Every file under `dir`, as paths relative to `root`. */
function walk(root, dir = root) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(root, p) : [relative(root, p)];
  });
}

/** The files index.html loads before the app runs: entry + modulepreloads, and stylesheets. */
export function initialFiles(dist) {
  const html = readFileSync(join(dist, 'index.html'), 'utf8');
  const attr = (tag, name) => tag.match(new RegExp(`${name}="([^"]+)"`))?.[1];
  const clean = (href) => href.replace(/^\.\//, '');
  const js = [];
  const css = [];
  for (const tag of html.match(/<(script|link)\b[^>]*>/g) ?? []) {
    if (tag.startsWith('<script') && attr(tag, 'type') === 'module' && attr(tag, 'src')) js.push(clean(attr(tag, 'src')));
    else if (tag.startsWith('<link') && attr(tag, 'rel') === 'modulepreload') js.push(clean(attr(tag, 'href')));
    else if (tag.startsWith('<link') && attr(tag, 'rel') === 'stylesheet') css.push(clean(attr(tag, 'href')));
  }
  return { js, css };
}

/** Raw, gzip (level 9) and brotli (quality 9) sizes of a buffer. */
export function compressedSizes(buf) {
  return {
    raw: buf.length,
    gzip: gzipSync(buf, { level: 9 }).length,
    brotli: brotliCompressSync(buf, { params: { [constants.BROTLI_PARAM_QUALITY]: 9 } }).length,
  };
}

/** Classifies a built file by how and when the app loads it. */
function kindOf(f, initial) {
  if (initial.js.includes(f)) return 'initial-js';
  if (initial.css.includes(f)) return 'initial-css';
  if (/\.wasm$/.test(f)) return 'wasm';
  if (/\.(woff2?|ttf|otf)$/.test(f)) return 'font';
  if (/(^|\/)(sw\.js|manifest\.webmanifest|engines\.json)$/.test(f) || f.startsWith('icons/') || f === 'index.html') return 'shell';
  if (/worker|\.mjs$/i.test(f)) return 'worker-js';
  if (/\.js$/.test(f)) return 'lazy-js';
  if (/\.css$/.test(f)) return 'lazy-css';
  if (/\.(onnx|bin|task|tflite|litertlm|gguf|safetensors)$/.test(f)) return 'model';
  return 'other';
}

/** Sizes of every built file grouped by kind; `initial` lists what index.html loads up front. */
export function report(distDir) {
  const dist = resolve(distDir);
  if (!existsSync(join(dist, 'index.html'))) throw new Error(`No index.html in ${dist}. Build first: npx vite build`);
  const initial = initialFiles(dist);
  const everything = walk(dist);
  const files = everything.filter((f) => !f.endsWith('.map')).map((f) => ({ file: f, kind: kindOf(f, initial), ...compressedSizes(readFileSync(join(dist, f))) }));
  const sum = (list, k) => list.reduce((n, f) => n + f[k], 0);
  const groups = {};
  for (const f of files) (groups[f.kind] ??= []).push(f);
  const totals = Object.fromEntries(Object.entries(groups).map(([k, list]) => [k, { files: list.length, raw: sum(list, 'raw'), gzip: sum(list, 'gzip'), brotli: sum(list, 'brotli') }]));
  const maps = everything.filter((f) => f.endsWith('.map'));
  totals.sourcemaps = { files: maps.length, raw: maps.reduce((n, f) => n + statSync(join(dist, f)).size, 0), gzip: 0, brotli: 0 };
  totals.everything = { files: files.length, raw: sum(files, 'raw'), gzip: sum(files, 'gzip'), brotli: sum(files, 'brotli') };
  return { dist, initial, files, totals };
}

// ---- Attribution (--why) -------------------------------------------------------------------------

const B64 = Object.fromEntries([...'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'].map((c, i) => [c, i]));

/** Decodes one VLQ-encoded source-map segment into its integer fields. */
function vlq(segment) {
  const out = [];
  let value = 0;
  let shift = 0;
  for (const ch of segment) {
    const digit = B64[ch];
    value += (digit & 31) << shift;
    if (digit & 32) shift += 5;
    else {
      out.push(value & 1 ? -(value >>> 1) : value >>> 1);
      value = 0;
      shift = 0;
    }
  }
  return out;
}

/** Generated bytes per original source for one chunk, from its source map. */
function attribute(dist, file) {
  const mapPath = join(dist, file + '.map');
  if (!existsSync(mapPath)) return {};
  const map = JSON.parse(readFileSync(mapPath, 'utf8'));
  const code = readFileSync(join(dist, file), 'utf8').split('\n');
  const bytes = {};
  let src = 0; // source index is delta-encoded across the whole mappings string
  map.mappings.split(';').forEach((line, row) => {
    const text = code[row] ?? '';
    let col = 0; // generated column resets every line
    const starts = [];
    for (const seg of line ? line.split(',').map(vlq) : []) {
      col += seg[0];
      if (seg.length >= 4) src += seg[1];
      starts.push([col, seg.length >= 4 ? src : -1]);
    }
    starts.forEach(([c, s], i) => {
      const end = i + 1 < starts.length ? starts[i + 1][0] : text.length;
      const name = s >= 0 ? map.sources[s] : '(unmapped)';
      bytes[name] = (bytes[name] ?? 0) + Math.max(0, end - c);
    });
  });
  return bytes;
}

/** Groups a source path by npm package, or by top-level app folder for first-party code. */
function owner(source) {
  const s = source.replace(/\\/g, '/');
  const nm = s.lastIndexOf('node_modules/');
  if (nm >= 0) {
    const rest = s.slice(nm + 13).split('/');
    return rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0];
  }
  const pkg = s.match(/packages\/([^/]+)\//);
  if (pkg) return `@inkwright/${pkg[1]}`;
  const app = s.match(/(?:^|\/)src\/(.+)$/);
  if (app) {
    const parts = app[1].split('/');
    return `src/${parts.length > 1 ? parts[0] + '/' : parts[0]}`;
  }
  return s;
}

/** Initial JS bytes by origin (package or app folder), and by single source file. */
export function why(r) {
  const byOwner = {};
  const bySource = {};
  for (const f of r.initial.js) {
    for (const [src, n] of Object.entries(attribute(r.dist, f))) {
      const o = owner(src);
      byOwner[o] = (byOwner[o] ?? 0) + n;
      bySource[src] = (bySource[src] ?? 0) + n;
    }
  }
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort((a, b) => b[1] - a[1]));
  return { byOwner: sorted(byOwner), bySource: sorted(bySource) };
}

// ---- CLI -----------------------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  const valueFlags = ['--json', '--top'];
  const opt = (name) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const positional = args.filter((a, i) => !a.startsWith('--') && !valueFlags.includes(args[i - 1]));
  const top = Number(opt('--top') ?? 25);
  const r = report(positional[0] ?? 'dist');
  // Decimal units, as Vite reports them (1 kB = 1000 bytes).
  const kb = (n) => `${(n / 1000).toFixed(1)} kB`;
  const fmt = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(2)} MB` : kb(n));

  console.log(`Bundle report: ${relative(process.cwd(), r.dist) || '.'}\n`);
  console.log('group'.padEnd(14), 'files'.padStart(5), 'raw'.padStart(12), 'gzip'.padStart(12), 'brotli'.padStart(12));
  for (const [k, t] of Object.entries(r.totals)) {
    console.log(k.padEnd(14), String(t.files).padStart(5), fmt(t.raw).padStart(12), (t.gzip ? fmt(t.gzip) : '-').padStart(12), (t.brotli ? fmt(t.brotli) : '-').padStart(12));
  }
  console.log(`\nInitial JS (${r.initial.js.length} files):`);
  for (const f of r.files.filter((f) => f.kind === 'initial-js').sort((a, b) => b.gzip - a.gzip).slice(0, top)) {
    console.log(`  ${kb(f.gzip).padStart(10)} gz  ${kb(f.raw).padStart(11)}  ${f.file}`);
  }
  console.log('\nLargest lazy files:');
  for (const f of r.files.filter((f) => !f.kind.startsWith('initial')).sort((a, b) => b.raw - a.raw).slice(0, top)) {
    console.log(`  ${fmt(f.raw).padStart(10)}  ${fmt(f.gzip).padStart(10)} gz  ${f.kind.padEnd(10)} ${f.file}`);
  }
  let attribution = null;
  if (args.includes('--why')) {
    attribution = why(r);
    console.log('\nInitial JS by origin (minified bytes):');
    for (const [o, n] of Object.entries(attribution.byOwner).slice(0, top)) console.log(`  ${kb(n).padStart(10)}  ${o}`);
    if (args.includes('--files')) {
      console.log('\nLargest initial sources:');
      for (const [s, n] of Object.entries(attribution.bySource).slice(0, top)) console.log(`  ${kb(n).padStart(10)}  ${s}`);
    }
  }
  const json = opt('--json');
  if (json) {
    writeFileSync(json, JSON.stringify({ ...r, dist: relative(process.cwd(), r.dist), why: attribution }, null, 2));
    console.log(`\nWrote ${json}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
